SELECT 
    ст.[Рег_номер],
    ст.[Фамилия],
    COUNT(э.[Оценка]) AS [Количество экзаменов],
    AVG(э.[Оценка]) AS [Средний балл]
FROM [Студент] ст
JOIN [Экзамен] э ON ст.[Рег_номер] = э.[Рег_номер]
GROUP BY ст.[Рег_номер], ст.[Фамилия]
HAVING AVG(э.[Оценка]) >= 4;

