SELECT
    А.Название,
    А.Континент,
    ROUND((А.Площадь * 100.0) / (
        SELECT SUM(Б.Площадь)
        FROM Страна Б
        WHERE Б.Континент = А.Континент
    ), 2) AS Процент_от_континента
FROM Страна А
ORDER BY А.Континент, Процент_от_континента DESC;

