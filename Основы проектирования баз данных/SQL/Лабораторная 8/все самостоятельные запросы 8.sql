SELECT
    Название,
    Площадь,
    Население,
    ROUND(Население / Площадь, 2) AS Плотность
FROM Страна
WHERE
    Население / Площадь > (SELECT AVG(Население / Площадь) FROM Страна)
    AND Площадь > 0 
ORDER BY Плотность DESC;

