SELECT Название
FROM Страна
WHERE Название LIKE '_а%' OR
      Название LIKE '_о%' OR
      Название LIKE '_у%' OR
      Название LIKE '_э%' OR
      Название LIKE '_ы%' OR
      Название LIKE '_и%' OR
      Название LIKE '_е%' OR
      Название LIKE '_ё%' OR
      Название LIKE '_ю%' OR
      Название LIKE '_я%';
