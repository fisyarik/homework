-- Удаляем процедуру, если она уже существует
DROP PROC IF EXISTS Пример8;
GO

-- Создаём процедуру
CREATE PROC Пример8
AS
BEGIN
    DECLARE @K AS INT;

    -- Проверяем существование таблицы Страны_У
    IF OBJECT_ID('Страны_У') IS NOT NULL
    BEGIN
        -- Считаем количество строк в таблице
        SELECT @K = COUNT(*) FROM Страны_У;

        -- Удаляем таблицу
        DROP TABLE Страны_У;
    END
    ELSE
    BEGIN
        -- Если таблицы нет, устанавливаем количество строк = 0
        SET @K = 0;
    END;

    -- Возвращаем количество строк
    RETURN @K;
END
GO

-- Вызываем процедуру и получаем результат
DECLARE @C AS INT;
EXEC @C = Пример8;
SELECT @C AS [Количество строк в удалённой таблице];
