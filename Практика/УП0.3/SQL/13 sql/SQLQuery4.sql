-- Удаляем процедуру, если она уже существует
DROP PROC IF EXISTS Пример4;
GO

-- Создаём процедуру с корректными параметрами и структурой
CREATE PROC Пример4
    @A AS FLOAT,
    @B AS FLOAT
AS
BEGIN
    SELECT
        Название,
        Столица,
        Площадь,
        Население,
        Континент
    FROM
        Страны
    WHERE
        Площадь BETWEEN @A AND @B;
END
GO

-- Вызываем процедуру с тестовыми параметрами
EXEC Пример4 1000, 10000;
