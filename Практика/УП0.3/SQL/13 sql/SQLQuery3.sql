-- Удаляем процедуру, если она уже существует
DROP PROC IF EXISTS Пример3;
GO

-- Создаём процедуру с корректным именем столбца
CREATE PROC Пример3
    @Конт AS VARCHAR(50)
AS
BEGIN
    SELECT
        Название,
        Столица,
        Площадь,
        Население
    FROM
        Страны
    WHERE
        Континент = @Конт;
END
GO

-- Вызываем процедуру
EXEC Пример3 'Азия';
