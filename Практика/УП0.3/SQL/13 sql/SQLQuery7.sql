-- Удаляем процедуру, если она уже существует
DROP PROC IF EXISTS Пример7;
GO

-- Создаём процедуру
CREATE PROC Пример7
AS
BEGIN
    -- Удаляем таблицу Страны_У, если она уже существует
    IF OBJECT_ID('Страны_У') IS NOT NULL
        DROP TABLE Страны_У;

    -- Создаём новую таблицу Страны_У и заполняем её данными
    SELECT
        Название,
        Столица,
        Площадь,
        Население,
        Континент
    INTO Страны_У
    FROM Страны
    WHERE LEFT(Название, 1) = 'У';
END
GO

-- Вызываем процедуру
EXEC Пример7;
